-- ========================================================
-- 0. 建立與初始化資料庫
-- ========================================================
CREATE DATABASE IF NOT EXISTS `calender` DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE `calender`;

-- 刪除舊資料表（若存在則重新建立）
DROP TABLE IF EXISTS `calendar_event_details`;
DROP TABLE IF EXISTS `calendar_event_categories`;
DROP TABLE IF EXISTS `calendar_holidays`;
DROP TABLE IF EXISTS `calendar_years_meta`;

-- ========================================================
-- 1. 建立資料表結構
-- ========================================================

-- 年份與生肖主題元資料表
CREATE TABLE `calendar_years_meta` (
  `year` INT PRIMARY KEY,
  `minguo_year` INT NOT NULL,
  `ganzhi` VARCHAR(10) NOT NULL,
  `theme` VARCHAR(20) NOT NULL,
  `animal` VARCHAR(10) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 假日與特殊節日資料表
CREATE TABLE `calendar_holidays` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `holiday_date` DATE NOT NULL,
  `title` VARCHAR(50) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 事件分類資料表
CREATE TABLE `calendar_event_categories` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `category_name` VARCHAR(50) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 行程活動詳細資料表
CREATE TABLE `calendar_event_details` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `event_date` DATE NOT NULL,
  `category_id` INT NOT NULL,
  `title` VARCHAR(100) NOT NULL,
  `content` TEXT,
  FOREIGN KEY (`category_id`) REFERENCES `calendar_event_categories`(`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;


